pub fn policy(channel: &str) -> Option<&'static ChannelPolicy> {
    POLICY
        .binary_search_by(|row| row.channel.cmp(channel))
        .ok()
        .map(|index| &POLICY[index])
}

pub fn console_channels() -> impl Iterator<Item = &'static str> {
    POLICY
        .iter()
        .filter(|row| row.callers.cli)
        .map(|row| row.channel)
}

