use super::caller::Caller;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Effect {
    Read,
    Act,
    Loosen,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Scope {
    Any,
    Dialog(&'static str),
    Run(&'static str),
    Shell(&'static str),
    Owner(&'static str),
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Callers {
    pub studio: bool,
    pub cli: bool,
    pub browser_ui: bool,
    pub panel: bool,
}

impl Callers {
    pub const fn admits(self, caller: Caller) -> bool {
        match caller {
            Caller::Studio => self.studio,
            Caller::Cli { .. } => self.cli,
            Caller::BrowserUi => self.browser_ui,
            Caller::Panel => self.panel,
        }
    }
}

const STUDIO: Callers = Callers {
    studio: true,
    cli: false,
    browser_ui: false,
    panel: false,
};

const CONSOLE: Callers = Callers {
    studio: true,
    cli: true,
    browser_ui: false,
    panel: false,
};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ChannelPolicy {
    pub channel: &'static str,
    pub callers: Callers,
    pub effect: Effect,
    pub scope: Scope,
}

const fn studio(channel: &'static str, effect: Effect) -> ChannelPolicy {
    ChannelPolicy {
        channel,
        callers: STUDIO,
        effect,
        scope: Scope::Any,
    }
}

const fn console(channel: &'static str, effect: Effect, scope: Scope) -> ChannelPolicy {
    ChannelPolicy {
        channel,
        callers: CONSOLE,
        effect,
        scope,
    }
}

